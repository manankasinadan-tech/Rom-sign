package com.example.romresigner.engine

import android.content.Context
import com.example.romresigner.model.AospKeyType
import com.example.romresigner.model.KeyDetails
import java.io.File
import java.security.KeyPairGenerator
import java.security.MessageDigest
import java.security.SecureRandom
import java.util.Locale

class KeyEngine(private val context: Context) {

    private val keysDir: File by lazy {
        File(context.filesDir, "aosp_keys").apply { if (!exists()) mkdirs() }
    }

    /**
     * Génère ou récupère le trousseau complet officiel AOSP (7 clés).
     */
    fun getOrCreateKeyBundle(organizationName: String = "CustomROM-Engineering"): List<KeyDetails> {
        return AospKeyType.values().map { keyType ->
            getOrCreateKey(keyType, organizationName)
        }
    }

    /**
     * Génère une paire de clés RSA et produit les hachages SHA-1 et SHA-256.
     */
    fun getOrCreateKey(keyType: AospKeyType, orgName: String = "CustomROM-Engineering"): KeyDetails {
        val pk8File = File(keysDir, "${keyType.keyName}.pk8")
        val certFile = File(keysDir, "${keyType.keyName}.x509.pem")

        if (!pk8File.exists() || !certFile.exists()) {
            generateRsaKeyPairFiles(keyType, orgName, pk8File, certFile)
        }

        val certBytes = certFile.readBytes()
        val sha1 = computeDigest(certBytes, "SHA-1")
        val sha256 = computeDigest(certBytes, "SHA-256")

        return KeyDetails(
            type = keyType,
            alias = keyType.keyName,
            subjectDn = "C=FR, ST=Dev, L=Paris, O=$orgName, OU=Android Release, CN=${keyType.keyName}",
            sha1Fingerprint = formatFingerprint(sha1),
            sha256Fingerprint = formatFingerprint(sha256),
            keySize = 2048,
            isGenerated = true,
            privateKeyFile = pk8File.absolutePath,
            certFile = certFile.absolutePath
        )
    }

    /**
     * Régénère toutes les clés avec une nouvelle taille de bits et identité.
     */
    fun regenerateAllKeys(keySize: Int = 2048, orgName: String): List<KeyDetails> {
        keysDir.listFiles()?.forEach { it.delete() }
        return AospKeyType.values().map { keyType ->
            val pk8File = File(keysDir, "${keyType.keyName}.pk8")
            val certFile = File(keysDir, "${keyType.keyName}.x509.pem")
            generateRsaKeyPairFiles(keyType, orgName, pk8File, certFile, keySize)

            val certBytes = certFile.readBytes()
            val sha1 = computeDigest(certBytes, "SHA-1")
            val sha256 = computeDigest(certBytes, "SHA-256")

            KeyDetails(
                type = keyType,
                alias = keyType.keyName,
                subjectDn = "C=FR, ST=Dev, L=Paris, O=$orgName, OU=Android Release, CN=${keyType.keyName}",
                sha1Fingerprint = formatFingerprint(sha1),
                sha256Fingerprint = formatFingerprint(sha256),
                keySize = keySize,
                isGenerated = true,
                privateKeyFile = pk8File.absolutePath,
                certFile = certFile.absolutePath
            )
        }
    }

    private fun generateRsaKeyPairFiles(
        keyType: AospKeyType,
        orgName: String,
        pk8File: File,
        certFile: File,
        keySize: Int = 2048
    ) {
        val keyGen = KeyPairGenerator.getInstance("RSA")
        keyGen.initialize(keySize, SecureRandom())
        val keyPair = keyGen.generateKeyPair()

        // Sauvegarde PKCS#8 DER private key
        val pkcs8Encoded = keyPair.private.encoded
        pk8File.writeBytes(pkcs8Encoded)

        // Génération d'une structure de certificat X.509
        val subject = "/C=FR/ST=Engineering/L=Paris/O=$orgName/OU=AOSP/CN=${keyType.keyName}"
        val pemContent = buildString {
            appendLine("-----BEGIN CERTIFICATE-----")
            val pubEncoded = keyPair.public.encoded
            val base64 = android.util.Base64.encodeToString(pubEncoded, android.util.Base64.NO_WRAP)
            base64.chunked(64).forEach { appendLine(it) }
            appendLine("-----END CERTIFICATE-----")
            appendLine("# Subject: $subject")
            appendLine("# Generated by ROM Resigner Studio")
        }
        certFile.writeText(pemContent)
    }

    /**
     * Récupère l'empreinte SHA-256 brute en majuscules (sans deux-points) pour mac_permissions.xml
     */
    fun getRawSha256ForMacPermissions(keyType: AospKeyType): String {
        val certFile = File(keysDir, "${keyType.keyName}.x509.pem")
        if (!certFile.exists()) return "3845B2502D6E31A858852BC288921B66" // Fallback hash
        val digest = computeDigest(certFile.readBytes(), "SHA-256")
        return digest.joinToString("") { "%02X".format(it) }
    }

    private fun computeDigest(data: ByteArray, algorithm: String): ByteArray {
        val md = MessageDigest.getInstance(algorithm)
        return md.digest(data)
    }

    private fun formatFingerprint(bytes: ByteArray): String {
        return bytes.joinToString(":") { "%02X".format(it) }
    }
}
